#!/usr/bin/env python3
"""Writes the Docker files that depend on config.yml, from the live config.

- docker-compose.override.yml: one read-only mount per library, at the same path inside the
  container, so the library paths work unchanged there and absolute symlinks keep resolving.
- config.container.yml: the config the container runs with. Its libraries are the same, but its
  data goes under /app/var (mounted from Server/var) and it listens on the port the container exposes.

Both files are git-ignored; the container config also holds the secrets. Rerun this after changing
a library in config.yml (make docker-config does). Needs PyYAML (python3-yaml).
"""
import argparse
import copy
import json
import os
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is needed to read config.yml: install python3-yaml (or pip install pyyaml).")

DOCKER_DIR = os.path.dirname(os.path.abspath(__file__))
SERVER_DIR = os.path.dirname(DOCKER_DIR)
CONTAINER_PORT = 9000

# Storage folders the container keeps under /app/var, keyed by their config name
MEDIA_DIRS = {
    "thumbnailPath": "thumbnails",
    "trickplayPath": "trickplay",
    "artworkPath": "artwork",
    "downloadPath": "downloads",
    "subtitlePath": "subtitles",
}


def library_folders(config):
    """Each library's folder on this machine. Relative paths are from Server/, as the live server reads them."""
    libraries, errors = [], []
    for library in config["media"]["paths"]:
        path = library["path"]
        # Normalized, not symlink-resolved: the mount must use the path the config names
        host = os.path.normpath(path if os.path.isabs(path) else os.path.join(SERVER_DIR, path))
        # Docker would create a missing folder empty, so the library would just look empty
        if not os.path.isdir(host):
            errors.append(f"library {library['name']!r}: {host} is not a folder")
        libraries.append((library, host))
    if errors:
        print("Not writing the Docker files:", *errors, sep="\n  ", file=sys.stderr)
        sys.exit(1)
    return libraries


def parse_user(text):
    uid, sep, gid = text.partition(":")
    if not (sep and uid.isdigit() and gid.isdigit()):
        sys.exit(f"Expected uid:gid as numbers, got {text!r}")
    return f"{uid}:{gid}"


def ask_user(current):
    print("How should the server run inside the container?")
    print(f"  1) As you ({current}): it can read the libraries and write Server/var (recommended)")
    print("  2) As root, the image's default: files it writes to Server/var end up owned by root")
    print("  3) As another user: enter uid:gid")
    choice = input("Choice [1]: ").strip() or "1"
    if choice == "1":
        return current
    if choice == "2":
        return "0:0"
    if choice == "3":
        return parse_user(input("uid:gid: ").strip())
    sys.exit(f"Not a choice: {choice!r}")


def choose_user(arg):
    """The uid:gid the container runs as: from --user, else asked on a terminal, else you."""
    current = f"{os.getuid()}:{os.getgid()}"
    if arg is None:
        if not sys.stdin.isatty():
            print(f"No terminal to ask, so running as you ({current}). Use --user to choose.")
            return current
        return ask_user(current)
    if arg == "current":
        return current
    if arg == "root":
        return "0:0"
    return parse_user(arg)


def check_access(libraries, user):
    """Warns when the chosen user can't read a library or write Server/var. Only checkable as yourself."""
    uid = int(user.split(":")[0])
    if uid == 0:  # root reads and writes anything
        return
    if uid != os.getuid():
        print(f"Not checking folder permissions for uid {uid}. It must read the libraries and write Server/var.")
        return
    for library, host in libraries:
        if not os.access(host, os.R_OK | os.X_OK):
            print(f"warning: library {library['name']!r} ({host}) isn't readable by you, so the container can't read it")
    if not os.access(os.path.join(SERVER_DIR, "var"), os.W_OK):
        print("warning: Server/var isn't writable by you, so the container can't store its data there")


def write_override(libraries, user):
    lines = [
        "# Generated by docker/generate.py from config.yml. Rerun it after changing the libraries.",
        "services:",
        "  weirdstreamer:",
        f'    user: "{user}"',
    ]
    if libraries:
        lines.append("    volumes:")
        for _, host in libraries:
            # JSON strings are valid YAML, so json.dumps quotes paths with spaces safely
            lines.append(f"      - {json.dumps(f'{host}:{host}:ro')}")
    else:
        lines.append("    volumes: []")
    with open(os.path.join(DOCKER_DIR, "docker-compose.override.yml"), "w") as f:
        f.write("\n".join(lines) + "\n")


def write_container_config(config, libraries):
    container = copy.deepcopy(config)
    server = container["server"]
    server["host"] = "0.0.0.0"
    server["port"] = CONTAINER_PORT
    # The container has no certificate; without one the server falls back to plain HTTP
    server["certFile"] = ""
    server["keyFile"] = ""
    server["logsPath"] = "/app/var/logs"
    container["database"]["userPath"] = "/app/var/data/users.db"
    container["database"]["mediaPath"] = "/app/var/data/media.db"
    for key, name in MEDIA_DIRS.items():
        container["media"][key] = f"/app/var/{name}"
    for library, (_, host) in zip(container["media"]["paths"], libraries):
        library["path"] = host
    # Owner-only: the file holds the TMDB token and the JWT secret
    path = os.path.join(DOCKER_DIR, "config.container.yml")
    if os.path.exists(path):
        os.remove(path)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("# Generated by docker/generate.py from config.yml: edit that, then rerun make docker-config.\n")
        yaml.safe_dump(container, f, sort_keys=False, allow_unicode=True)


def main():
    parser = argparse.ArgumentParser(description="Write the Docker files from config.yml.")
    parser.add_argument("--user", help="run the container as: current (you), root, or uid:gid. "
                                       "Asked on a terminal when left out.")
    args = parser.parse_args()

    with open(os.path.join(SERVER_DIR, "config.yml")) as f:
        config = yaml.safe_load(f)
    libraries = library_folders(config)
    user = choose_user(args.user)
    # Made here, not by Docker: a folder Docker creates is owned by root
    os.makedirs(os.path.join(SERVER_DIR, "var"), exist_ok=True)
    check_access(libraries, user)
    write_override(libraries, user)
    write_container_config(config, libraries)
    print(f"Container runs as {user}.")
    print(f"Wrote docker/docker-compose.override.yml ({len(libraries)} library mounts)")
    print("Wrote docker/config.container.yml")


if __name__ == "__main__":
    main()
